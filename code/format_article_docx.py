"""Apply the publication style used by the Word and PDF article editions.

The source document is generated by Pandoc so equations, links, Markdown
tables, and code remain semantically structured. This script then applies a
small, deterministic visual system and inserts the article cover.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from docx import Document
from docx.enum.section import WD_SECTION
from docx.enum.table import WD_CELL_VERTICAL_ALIGNMENT, WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Pt, RGBColor


INK = "111111"
NAVY = "18324A"
PALE = "EEF3F7"
GRID = "D9D9D9"


def set_cell_fill(cell, color: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = tc_pr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tc_pr.append(shd)
    shd.set(qn("w:fill"), color)


def set_cell_margins(cell, top=100, start=110, bottom=100, end=110) -> None:
    tc = cell._tc
    tc_pr = tc.get_or_add_tcPr()
    tc_mar = tc_pr.first_child_found_in("w:tcMar")
    if tc_mar is None:
        tc_mar = OxmlElement("w:tcMar")
        tc_pr.append(tc_mar)
    for edge, value in (("top", top), ("start", start), ("bottom", bottom), ("end", end)):
        tag = "w:" + edge
        node = tc_mar.find(qn(tag))
        if node is None:
            node = OxmlElement(tag)
            tc_mar.append(node)
        node.set(qn("w:w"), str(value))
        node.set(qn("w:type"), "dxa")


def set_table_borders(table) -> None:
    tbl_pr = table._tbl.tblPr
    borders = tbl_pr.find(qn("w:tblBorders"))
    if borders is None:
        borders = OxmlElement("w:tblBorders")
        tbl_pr.append(borders)
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        node = borders.find(qn("w:" + edge))
        if node is None:
            node = OxmlElement("w:" + edge)
            borders.append(node)
        node.set(qn("w:val"), "single")
        node.set(qn("w:sz"), "4")
        node.set(qn("w:color"), GRID)


def set_repeat_table_header(row) -> None:
    tr_pr = row._tr.get_or_add_trPr()
    tbl_header = OxmlElement("w:tblHeader")
    tbl_header.set(qn("w:val"), "true")
    tr_pr.append(tbl_header)


def add_page_number(paragraph) -> None:
    paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    run = paragraph.add_run()
    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    instruction = OxmlElement("w:instrText")
    instruction.set(qn("xml:space"), "preserve")
    instruction.text = " PAGE "
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    run._r.extend((begin, instruction, end))
    run.font.name = "Aptos"
    run.font.size = Pt(9)
    run.font.color.rgb = RGBColor.from_string("666666")


def style_document(source: Path, destination: Path, cover: Path) -> None:
    doc = Document(source)

    section = doc.sections[0]
    section.page_width = Inches(8.5)
    section.page_height = Inches(11)
    section.top_margin = Inches(0.72)
    section.bottom_margin = Inches(0.70)
    section.left_margin = Inches(0.78)
    section.right_margin = Inches(0.78)

    normal = doc.styles["Normal"]
    normal.font.name = "Aptos"
    normal.font.size = Pt(10.5)
    normal.font.color.rgb = RGBColor.from_string(INK)
    normal.paragraph_format.space_after = Pt(6)
    normal.paragraph_format.line_spacing = 1.08

    # Pandoc uses Body Text and First Paragraph for most prose.
    for style_name in ("Body Text", "First Paragraph"):
        style = doc.styles[style_name]
        style.font.name = "Aptos"
        style.font.size = Pt(10.5)
        style.font.color.rgb = RGBColor.from_string(INK)
        style.paragraph_format.space_after = Pt(6)
        style.paragraph_format.line_spacing = 1.08

    for level, size in ((1, 25), (2, 16), (3, 12.5)):
        style_name = f"Heading {level}"
        # Pandoc omits unused heading levels from some generated style sets.
        matching = [s for s in doc.styles if s.name == style_name]
        if not matching:
            continue
        style = matching[0]
        style.font.name = "Aptos Display"
        style.font.size = Pt(size)
        style.font.bold = True
        style.font.color.rgb = RGBColor(0, 0, 0)
        style.paragraph_format.keep_with_next = True
        style.paragraph_format.space_before = Pt(15 if level > 1 else 0)
        style.paragraph_format.space_after = Pt(6)

    # The Markdown title begins as Heading 1. Convert it to a true Word title.
    title = doc.paragraphs[0]
    title.style = doc.styles["Title"]
    title.alignment = WD_ALIGN_PARAGRAPH.LEFT
    title.paragraph_format.space_after = Pt(5)
    for run in title.runs:
        run.font.name = "Aptos Display"
        run.font.size = Pt(28)
        run.font.bold = True
        run.font.color.rgb = RGBColor(0, 0, 0)

    subtitle = doc.paragraphs[1]
    subtitle.alignment = WD_ALIGN_PARAGRAPH.LEFT
    subtitle.paragraph_format.space_after = Pt(10)
    for run in subtitle.runs:
        run.font.name = "Aptos"
        run.font.size = Pt(13)
        run.font.italic = True
        run.font.color.rgb = RGBColor.from_string("3F4E59")

    # Place the cover after the subtitle without turning the document into a
    # decorative magazine layout; the evidence remains the visual priority.
    image_paragraph = doc.paragraphs[2].insert_paragraph_before()
    image_paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    image_paragraph.paragraph_format.space_after = Pt(10)
    image_paragraph.add_run().add_picture(str(cover), width=Inches(6.65))

    # Block quote style: restrained italic with left indentation, no box.
    if "Block Text" in doc.styles:
        block = doc.styles["Block Text"]
        block.font.name = "Aptos"
        block.font.size = Pt(10.5)
        block.font.italic = True
        block.font.color.rgb = RGBColor.from_string("273746")
        block.paragraph_format.left_indent = Inches(0.28)
        block.paragraph_format.right_indent = Inches(0.18)
        block.paragraph_format.space_before = Pt(5)
        block.paragraph_format.space_after = Pt(8)

    if "Source Code" in doc.styles:
        code = doc.styles["Source Code"]
        code.font.name = "DejaVu Sans Mono"
        code.font.size = Pt(8.2)
        code.font.color.rgb = RGBColor.from_string(INK)
        code.paragraph_format.left_indent = Inches(0.12)
        code.paragraph_format.right_indent = Inches(0.12)
        code.paragraph_format.space_before = Pt(5)
        code.paragraph_format.space_after = Pt(8)

    # Apply subtle paragraph shading to code blocks.
    for paragraph in doc.paragraphs:
        if paragraph.style.name == "Source Code":
            p_pr = paragraph._p.get_or_add_pPr()
            shd = OxmlElement("w:shd")
            shd.set(qn("w:fill"), "F4F6F7")
            p_pr.append(shd)

    for table in doc.tables:
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        table.autofit = True
        set_table_borders(table)
        set_repeat_table_header(table.rows[0])
        for row_index, row in enumerate(table.rows):
            for cell in row.cells:
                cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
                set_cell_margins(cell)
                set_cell_fill(cell, NAVY if row_index == 0 else (PALE if row_index % 2 == 0 else "FFFFFF"))
                for paragraph in cell.paragraphs:
                    paragraph.paragraph_format.space_after = Pt(0)
                    paragraph.paragraph_format.line_spacing = 1.0
                    for run in paragraph.runs:
                        run.font.name = "Aptos"
                        run.font.size = Pt(8.5)
                        run.font.color.rgb = RGBColor(255, 255, 255) if row_index == 0 else RGBColor.from_string(INK)
                        if row_index == 0:
                            run.font.bold = True

    # Images generated for the article are already high-resolution. Ensure
    # captions/descriptions and images do not become isolated by page breaks.
    for paragraph in doc.paragraphs:
        if paragraph._p.xpath(".//w:drawing"):
            paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
            paragraph.paragraph_format.keep_with_next = False
            paragraph.paragraph_format.space_before = Pt(7)
            paragraph.paragraph_format.space_after = Pt(7)

    footer = section.footer.paragraphs[0]
    add_page_number(footer)

    # Give links conventional blue color but keep headings and title black.
    for paragraph in doc.paragraphs:
        if paragraph.style.name.startswith("Heading") or paragraph.style.name == "Title":
            continue
        for hyperlink in paragraph._p.xpath(".//w:hyperlink"):
            for run_node in hyperlink.xpath(".//w:r"):
                r_pr = run_node.get_or_add_rPr()
                color = r_pr.find(qn("w:color"))
                if color is None:
                    color = OxmlElement("w:color")
                    r_pr.append(color)
                color.set(qn("w:val"), "1F5A80")

    doc.core_properties.title = "When Better Predictions Arrive Later"
    doc.core_properties.subject = "A higher-education TabPFN case study"
    doc.core_properties.author = ""
    doc.core_properties.keywords = "TabPFN, higher education, evaluation, student retention"
    destination.parent.mkdir(parents=True, exist_ok=True)
    doc.save(destination)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    parser.add_argument("--cover", required=True, type=Path)
    parsed = parser.parse_args()
    style_document(parsed.source, parsed.destination, parsed.cover)


if __name__ == "__main__":
    main()
